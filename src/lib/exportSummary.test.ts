import assert from "node:assert/strict";
import { test } from "node:test";

import { BIOLOGY_SAMPLE, BIOLOGY_TEXT } from "@/samples/biology";
import { runEngine } from "./engine";
import { buildSummary, summaryFilename } from "./exportSummary";

test("a Korean title keeps its name in the filename", () => {
  assert.equal(summaryFilename("확산 실험: 농도 기울기"), "확산-실험-농도-기울기-accesslens.md");
});

test("characters a filesystem rejects are removed, and nothing else", () => {
  assert.equal(summaryFilename('Lab 3 / Part "A" <draft>?'), "Lab-3-Part-A-draft-accesslens.md");
  assert.equal(summaryFilename("..\..\secret"), "secret-accesslens.md");
});

test("an empty or reserved title still produces a usable name", () => {
  assert.equal(summaryFilename("  ///  "), "과제-accesslens.md");
  assert.equal(summaryFilename("CON"), "CON-과제-accesslens.md");
});

test("long titles are cut by character, never mid-syllable", () => {
  const name = summaryFilename("가".repeat(100));
  assert.equal(name, `${"가".repeat(60)}-accesslens.md`);
});

test("export labels are Korean while the assignment text stays in its own language", () => {
  const analysis = BIOLOGY_SAMPLE.analysis;
  const report = runEngine(analysis);
  const file = buildSummary(
    { kind: "original", title: "Diffusion Lab", text: BIOLOGY_TEXT },
    BIOLOGY_SAMPLE.analysisObjective,
    { analysis, report, scoreBefore: 50, repairedAnalysis: analysis, repairedReport: report, scoreAfter: 50, frictionResolutions: [] },
  );
  for (const heading of ["## 원본 과제 (변경 없음)", "## 학습 목표 (교사가 확정함)", "## 측정값", "| | 원본 |"]) {
    assert.ok(file.includes(heading), heading);
  }
  assert.ok(file.includes(BIOLOGY_TEXT.trim()), "the English source must not be translated");
  assert.doesNotMatch(file, /Measurements|Learning objective|Generated by/);
  assert.match(file, /여유 있음|빠듯함|부족함|시간 제한 없음/);
});
